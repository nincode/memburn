pub fn glyph(c: char) -> Option<&'static Glyph> {
    match c {
        ' '..='~' => Some(&ASCII[c as usize - 32]),
        _ => EXTRA.binary_search_by_key(&c, |e| e.0).ok().map(|i| &EXTRA[i].1),
    }
}

/// `glyph(c)`, or '?' for a char the font lacks.
pub fn glyph_or_mark(c: char) -> &'static Glyph {
    glyph(c).unwrap_or(&ASCII[b'?' as usize - 32])
}

